import assert from 'node:assert/strict';
import { createHmac } from 'node:crypto';
const variables={SLACK_SIGNING_SECRET:'test-signing-secret'};
globalThis.Netlify={env:{get:k=>variables[k],toObject:()=>({...variables})}};
const {verify}=await import('./netlify/functions/_shared/runtime.mts');
const events=(await import('./netlify/functions/slack-events.mts')).default;
const api=(await import('./netlify/functions/audit-api.mts')).default;
const stamp=String(Math.floor(Date.now()/1000));
const raw=JSON.stringify({type:'url_verification',challenge:'challenge-value'});
const headers=new Headers({'x-slack-request-timestamp':stamp,'x-slack-signature':'v0='+createHmac('sha256',variables.SLACK_SIGNING_SECRET).update(`v0:${stamp}:${raw}`).digest('hex')});
assert(verify(raw,headers));assert(!verify(raw+'x',headers));assert(!verify(raw,headers,Date.now()+600000));
const short=new Headers(headers);short.set('x-slack-signature','v0=x');assert(!verify(raw,short));
const challenge=await events(new Request('https://example.invalid/slack/events',{method:'POST',headers,body:raw}),{});
assert.equal(await challenge.text(),'challenge-value');
assert.equal((await events(new Request('https://example.invalid/slack/events',{method:'POST',body:raw}),{})).status,401);
const health=await api(new Request('https://example.invalid/health'),{});assert.equal(health.status,503);assert.equal((await health.json()).enabled,false);
assert.equal((await api(new Request('https://example.invalid/api/jobs/test'),{})).status,401);
const service=await import('./server.js');assert.equal(typeof service.default.processSlackEvent,'function');assert.equal(typeof service.default.discrepancyResolutionWorkflow.blockAction,'function');
console.log('PASS: Slack signatures, replay rejection, URL challenge, disabled readiness, protected audit API, reusable server without listener.');
